const assert=require('node:assert/strict'),{analyze}=require('../tools/analyze-perf.cjs');
const spike={atMs:100,frameMs:100,bridge:{collect:10,'collect.scan':8,'collect.tracking':2,commands:1,localmap:1},gen0:1,gen1:0,gen2:0};
const sample=(at,uptimeMs,frames,spikes=[spike])=>({at,data:{uptimeMs,frames,frame:{p50:16,p95:100},bridge:{},spikes}});
const a=sample('2026-09-27T01:00:00Z',1000,10),b=sample('2026-09-27T01:01:00Z',61000,500);
const r=analyze([b,a]);
assert.equal(r.slowFrames.retainedUnique,1);assert.equal(r.slowFrames.measuredShareMedian,12);
assert.equal(r.slowFrames.withGc,1);assert.equal(r.slowFrames.recorderMissing,1);
assert.equal(r.elapsedSeconds,60);assert.equal(r.windows.length,2);assert.equal(r.frame,undefined);
assert.throws(()=>analyze([]));assert.throws(()=>analyze([a,sample(b.at,1,1)]),/mixed/);
const fixed={...spike,bridge:{...spike.bridge,'perf.frame':.1},gen0:0};
assert.equal(analyze([sample(a.at,1000,10,[fixed])]).slowFrames.recorderMissing,0);
assert.equal(r.slowFramesDuringSampling.retainedUnique,0);
assert.equal(r.slowFramesDuringSampling.measuredShareMedian,null);
const during={...fixed,atMs:2000},atBaseline={...fixed,atMs:1000},atEnd={...fixed,atMs:61000};
const bounded=analyze([a,sample(b.at,61000,500,[spike,atBaseline,during,atEnd])]);
assert.equal(bounded.slowFramesDuringSampling.retainedUnique,2);
assert.deepEqual(bounded.slowFramesDuringSampling.rows.map(s=>s.atMs),[2000,61000]);
assert.equal(bounded.slowFrames.retainedUnique,4);
assert.equal(bounded.slowFramesDuringSampling.recorderMissing,0);
assert.equal(analyze([a]).slowFramesDuringSampling.retainedUnique,0);
const scheduled={...fixed,bridge:{background:12,'background.tracking':12,'tracking.index':2,'tracking.residents':10,commands:1,localmap:1}};
assert.equal(analyze([sample(a.at,1000,10,[scheduled])]).slowFrames.measuredShareMedian,14);
assert.equal(r.hitchesDuringSampling,null);
const hitchSample={...b,data:{...b.data,hitches:[{...during,frameMs:30},{...spike,frameMs:30}]}};
assert.equal(analyze([a,hitchSample]).hitchesDuringSampling.retainedUnique,1);
assert.equal(analyze([a,hitchSample]).hitchesDuringSampling.rows[0].frameMs,30);
console.log('21 performance analysis checks passed');
