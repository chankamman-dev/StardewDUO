// A full icon cache must remain useful across more than one inventory's worth of IDs.
var cache=new BoundedCache<string,string?>(2);
cache["first"]="one";cache["second"]="two";
Check(cache.Count==2&&cache.ContainsKey("first"),"cache reaches exact capacity");
cache["third"]="three";
Check(cache.Count==2&&!cache.ContainsKey("first")&&cache.TryGetValue("third",out var third)&&third=="three","cache evicts oldest and accepts new icon");
Check(cache.TryGetValue("second",out var second)&&second=="two","cache read refreshes recency");
cache["fourth"]="four";
Check(cache.ContainsKey("second")&&!cache.ContainsKey("third")&&cache.Count==2,"recently read icon survives next eviction");
cache["second"]="updated";cache["fifth"]="five";
Check(cache.Count==2&&cache.TryGetValue("second",out var updated)&&updated=="updated"&&!cache.ContainsKey("fourth"),"replacement refreshes recency without phantom entries");
cache["failed"]=null;
Check(cache.TryGetValue("failed",out var failed)&&failed==null,"failed icon is cached instead of retried every scan");
cache.Clear();Check(cache.Count==0&&!cache.TryGetValue("failed",out _),"cache clear removes values and recency");
var many=new BoundedCache<int,int>(144);
for(int i=0;i<1000;i++)many[i]=i;
Check(many.Count==144&&!many.ContainsKey(0)&&many.TryGetValue(999,out var newest)&&newest==999,"cache remains bounded through 1000 distinct items");
many[0]=0;
Check(many.Count==144&&many.TryGetValue(0,out var revisited)&&revisited==0,"evicted item can be reacquired later");
